library(testthat)
library(umx)
library(OpenMx)

test_that("umxDoC prints fit only with pointer note", {
	oldSilent = umx_set_silent(FALSE)
	on.exit(umx_set_silent(oldSilent), add = TRUE)
	data(docData)
	mzData = subset(docData, zygosity %in% c("MZFF", "MZMM"))
	dzData = subset(docData, zygosity %in% c("DZFF", "DZMM"))
	var1 = paste0("varA", 1:3)
	var2 = paste0("varB", 1:3)
	msgs = character(0)
	out = capture.output(d1 <- withCallingHandlers(umxDoC(var1 = var1, var2 = var2, mzData = mzData, dzData = dzData, causal = TRUE), message = function(m) {
		msgs <<- c(msgs, conditionMessage(m))
		invokeRestart("muffleMessage")
	}), type = "output")
	all = c(out, msgs)
	expect_true(any(grepl("Model Fit Summary", all, fixed = TRUE)))
	expect_true(any(grepl("call umxSummary() or plot()", all, fixed = TRUE)))
	expect_false(any(grepl("FacLoad", all, fixed = TRUE)))
	expect_false(any(grepl("Table: Means", all, fixed = TRUE)))
	expect_false(any(grepl("Table: Causal paths", all, fixed = TRUE)))
	expect_true(isS4(d1))
	dmsgs = character(0)
	directOut = capture.output(vis <- withVisible(s <- withCallingHandlers(umxSummaryDoC(d1), message = function(m) {
		dmsgs <<- c(dmsgs, conditionMessage(m))
		invokeRestart("muffleMessage")
	})), type = "output")
	directAll = c(directOut, dmsgs)
	expect_false(any(grepl("not complete yet", directAll, fixed = TRUE)))
	expect_true(any(grepl("Table: Means", directAll, fixed = TRUE)))
	expect_true(any(grepl("FacLoad", directAll, fixed = TRUE)))
	expect_false(vis$visible)
	expect_true(isS4(vis$value))
})

