test_that("umxSexLim Homogeneity fits and reports", {
	require(umx)
	data("us_skinfold_data")
	mzmData = subset(us_skinfold_data, zyg == 1)
	mzfData = subset(us_skinfold_data, zyg == 2)
	dzmData = subset(us_skinfold_data, zyg == 3)
	dzfData = subset(us_skinfold_data, zyg == 4)
	dzoData = subset(us_skinfold_data, zyg == 5)
	oldSilent = umx_set_silent(FALSE)
	on.exit(umx_set_silent(oldSilent), add = TRUE)
	fitMsg = testthat::capture_messages(s1 <- umxSexLim(selDVs = "bic", sep = "_T", A_or_C = "A", sexlim = "Homogeneity", mzmData = mzmData, dzmData = dzmData, mzfData = mzfData, dzfData = dzfData, dzoData = dzoData))
	expect_true(umx_has_been_run(s1))
	expect_true(any(grepl("less tested", fitMsg, fixed = TRUE)))
	sumMsg = testthat::capture_messages(sumOut <- capture.output(umxSummary(s1, file = NA)))
	expect_true(any(grepl("expMeanGm and expMeanGf", sumOut, fixed = TRUE)))
	digMsg = testthat::capture_messages(dig <- umxPlotSexLim(s1, file = NA))
	expect_true(grepl("subgraph cluster_male", dig, fixed = TRUE))
	expect_true(grepl("M_bic", dig, fixed = TRUE))
	expect_true(grepl("F_bic", dig, fixed = TRUE))
	# raw solution table carries the Am/Af variance diagonals
	rawMsg = testthat::capture_messages(rawOut <- capture.output(umxSummary(s1, file = NA, std = FALSE)))
	expect_true(any(grepl("Raw solution", rawMsg, fixed = TRUE)))
	bicLine = grep("|bic", rawOut, value = TRUE, fixed = TRUE)
	expect_equal(length(bicLine), 1)
	bicNum = as.numeric(regmatches(bicLine, gregexpr("-?\\.?[0-9]+\\.?[0-9]*", bicLine))[[1]])
	expect_true(abs(bicNum[1] - diag(as.matrix(s1$top$Am$result))[1]) < 0.015)
	expect_true(abs(bicNum[2] - diag(as.matrix(s1$top$Af$result))[1]) < 0.015)
})

