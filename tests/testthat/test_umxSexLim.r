	expect_true(grepl("am1 -> am2", dig, fixed = TRUE))
	expect_true(grepl("color=purple", dig, fixed = TRUE))
})

test_that("umxReduceSexLim walks the limitation ladder", {
	require(umx)
	data("us_skinfold_data")
	mzmData = subset(us_skinfold_data, zyg == 1)
	mzfData = subset(us_skinfold_data, zyg == 2)
	dzmData = subset(us_skinfold_data, zyg == 3)
	dzfData = subset(us_skinfold_data, zyg == 4)
	dzoData = subset(us_skinfold_data, zyg == 5)
	optRun = getOption("umx_auto_run")
	optSilent = getOption("umx_silent")
	optFormat = getOption("umx.plot.format")
	on.exit({ options("umx_auto_run" = optRun); options("umx_silent" = optSilent); options("umx.plot.format" = optFormat) }, add = TRUE)
	s1 = umxSexLim(selDVs = "bic", sep = "_T", A_or_C = "A", mzmData = mzmData, dzmData = dzmData, mzfData = mzfData, dzfData = dzfData, dzoData = dzoData)
	redMsg = testthat::capture_messages(redOut <- capture.output(best <- umxReduce(s1)))
	expect_true(any(grepl("Scalar", redOut, fixed = TRUE)))
	expect_true(any(grepl("Homogeneity", redOut, fixed = TRUE)))
	expect_true(any(grepl("fit best according to AIC", redMsg, fixed = TRUE)))
	expect_true(any(grepl("intervals = TRUE", redMsg, fixed = TRUE)))
	expect_true(umx_has_been_run(best))
	expect_identical(getOption("umx_auto_run"), optRun)
	expect_identical(getOption("umx_silent"), optSilent)
	expect_identical(getOption("umx.plot.format"), optFormat)
})

